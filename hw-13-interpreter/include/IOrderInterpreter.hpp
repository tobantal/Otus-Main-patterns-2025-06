/**
 * @brief Интерфейс интерпретатора приказов
 * 
 * Определяет контракт для интерпретации и выполнения приказов.
 * Реализации могут добавлять дополнительную логику:
 * - проверку прав доступа
 * - логирование
 * - валидацию
 * - кэширование и т.д.
 */
class IOrderInterpreter {
public:
    /**
     * @brief Виртуальный деструктор
     */
    virtual ~IOrderInterpreter() = default;
    
    /**
     * @brief Интерпретирует и выполняет приказ
     * 
     * Метод должен:
     * 1. Валидировать приказ
     * 2. Найти целевой объект
     * 3. Создать соответствующую команду
     * 4. Выполнить команду
     * 
     * @param order Доменная модель приказа
     * @throws std::runtime_error при ошибке интерпретации:
     *         - невалидный приказ
     *         - объект не найден
     *         - неизвестное действие
     *         - ошибка выполнения команды
     */
    virtual void interpret(const Order& order) = 0;
};